// Пин для кнопки сброса в подвале: на ивенте рядом с гостем сидит проверяющий,
// он знает код и сбрасывает квиз для следующего человека.
//
// ВАЖНО: это не защита. Пин лежит в открытом JS, состояние попыток — в
// localStorage браузера гостя, серверной проверки нет. Код спасает от
// случайного тыка в кнопку, но не от того, кто откроет исходник или
// инкогнито-вкладку. Если лимит попыток станет по-настоящему важен
// (награда, призы) — считать его надо на сервере.
export const RESET_PIN = '2021';

export function isResetPin(input) {
  if (input === null || input === undefined) return false;
  return String(input).trim() === RESET_PIN;
}
